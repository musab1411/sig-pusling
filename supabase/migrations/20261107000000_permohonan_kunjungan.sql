-- ============================================================
-- Fitur Permohonan Kunjungan Perpustakaan Keliling
-- Jalankan file ini di Supabase Dashboard > SQL Editor
-- ============================================================

create table if not exists public.permohonan_kunjungan (
  id bigint generated by default as identity primary key,
  jenis_pemohon text not null default 'Masyarakat Umum'
    check (jenis_pemohon in ('Sekolah', 'Masyarakat Umum', 'Instansi/Organisasi')),
  nama_pemohon text not null,
  instansi text,
  kontak text not null,
  alamat_lokasi text not null,
  tanggal_kunjungan date not null,
  jam_kunjungan text not null,
  jumlah_peserta integer not null default 1 check (jumlah_peserta > 0),
  keperluan text,
  lat double precision,
  lng double precision,
  status text not null default 'menunggu'
    check (status in ('menunggu', 'disetujui', 'ditolak')),
  catatan_admin text,
  created_at timestamptz not null default now()
);

-- Untuk database yang tabelnya sudah dibuat sebelumnya.
alter table public.permohonan_kunjungan add column if not exists lat double precision;
alter table public.permohonan_kunjungan add column if not exists lng double precision;

alter table public.permohonan_kunjungan drop constraint if exists permohonan_kunjungan_coord_check;
alter table public.permohonan_kunjungan add constraint permohonan_kunjungan_coord_check
  check (
    (lat is null and lng is null)
    or (lat between -90 and 90 and lng between -180 and 180)
  );

create index if not exists permohonan_kunjungan_tanggal_idx
  on public.permohonan_kunjungan (tanggal_kunjungan);

create index if not exists permohonan_kunjungan_status_idx
  on public.permohonan_kunjungan (status);

-- ============================================================
-- HAK AKSES DASAR
-- ============================================================
grant usage on schema public to anon, authenticated;
grant insert on public.permohonan_kunjungan to anon, authenticated;
grant select, update, delete on public.permohonan_kunjungan to authenticated;
grant usage, select on sequence public.permohonan_kunjungan_id_seq to anon, authenticated;

-- ============================================================
-- ROW LEVEL SECURITY
-- ============================================================
alter table public.permohonan_kunjungan enable row level security;

-- Masyarakat (anon) boleh mengirim permohonan.
drop policy if exists "permohonan_insert_publik" on public.permohonan_kunjungan;
create policy "permohonan_insert_publik"
  on public.permohonan_kunjungan
  for insert
  to anon, authenticated
  with check (status = 'menunggu');

-- Admin (user yang login lewat Supabase Auth) boleh melihat & mengelola.
drop policy if exists "permohonan_admin_select" on public.permohonan_kunjungan;
create policy "permohonan_admin_select"
  on public.permohonan_kunjungan
  for select
  to authenticated
  using (true);

drop policy if exists "permohonan_admin_update" on public.permohonan_kunjungan;
create policy "permohonan_admin_update"
  on public.permohonan_kunjungan
  for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "permohonan_admin_delete" on public.permohonan_kunjungan;
create policy "permohonan_admin_delete"
  on public.permohonan_kunjungan
  for delete
  to authenticated
  using (true);

-- ============================================================
-- VIEW PUBLIK
-- Hanya menampilkan permohonan yang sudah disetujui dan
-- tanpa data kontak pribadi (nomor HP/email).
-- ============================================================
create or replace view public.permohonan_terjadwal as
select
  id,
  jenis_pemohon,
  nama_pemohon,
  instansi,
  tanggal_kunjungan,
  jam_kunjungan,
  alamat_lokasi,
  jumlah_peserta,
  keperluan,
  lat,
  lng
from public.permohonan_kunjungan
where status = 'disetujui';

grant select on public.permohonan_terjadwal to anon, authenticated;
